"""Build "Open Canvas.app", a double-clickable macOS app that starts the whole system.

Usage (from the repo root, venv active):
    python tools/make_mac_app.py                   # -> ~/Applications/Open Canvas.app

What the app is: a minimal app bundle whose program is a small zsh script. It runs this repo's
venv Python on app.main, finds the motor board's port itself (like start_open_canvas.command),
and writes its output to ~/Library/Logs/OpenCanvas.log instead of a Terminal window. The repo
path is baked in when the app is built, so rebuild it if the repo moves.

    Open Canvas.app/Contents/
        Info.plist          name, bundle ID, icon, and the camera permission prompt text
        MacOS/OpenCanvas    the launcher script
        Resources/AppIcon.icns

macOS asks for camera permission the first time (the prompt shows NSCameraUsageDescription).
Start it by double-click, Spotlight, the Dock, or Siri ("Hey Siri, Open Canvas" runs the
Shortcut, which can simply do: open -a "Open Canvas").
"""

import argparse
import os
import plistlib
import shutil
import subprocess
import tempfile

import cv2
import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

LAUNCHER = """#!/bin/zsh
# Open Canvas launcher (generated by tools/make_mac_app.py; edit that file, not this one)
REPO="{repo}"
LOG="$HOME/Library/Logs/OpenCanvas.log"
cd "$REPO" || {{ say "Open Canvas can't find its folder."; exit 1; }}

if pgrep -f "python.* -m app.main" >/dev/null; then
  say "Open Canvas is already running."
  exit 0
fi

# (N) = no error if a pattern matches nothing (zsh aborts the line otherwise)
ports=(/dev/cu.usbmodem*(N) /dev/cu.usbserial*(N))
{{
  echo "=== Open Canvas started $(date) ==="
  if [[ -n "${{ports[1]}}" ]]; then
    echo "[start] motor board on ${{ports[1]}}"
    exec "$REPO/.venv/bin/python" -u -m app.main --serial "${{ports[1]}}"
  else
    echo "[start] no motor board found: running without the motor"
    say "Motor not connected. Starting without it."
    exec "$REPO/.venv/bin/python" -u -m app.main
  fi
}} >>"$LOG" 2>&1
"""


def make_icon(out_icns):
    """App icon: the Sunset Hills painting in a rounded square with a fingertip dot."""
    art = cv2.imread(os.path.join(REPO, "content", "painting.png"))
    h, w = art.shape[:2]
    s = min(h, w)
    art = cv2.resize(art[(h - s) // 2:(h + s) // 2, (w - s) // 2:(w + s) // 2], (1024, 1024))
    # macOS icon grid: artwork is a rounded square inset ~10% from the 1024 canvas
    tile = cv2.resize(art, (824, 824))
    cv2.circle(tile, (560, 560), 60, (255, 255, 255), -1)          # fingertip touching the painting
    cv2.circle(tile, (560, 560), 60, (40, 40, 40), 8)
    mask = np.zeros((824, 824), np.uint8)
    r = 185
    cv2.rectangle(mask, (r, 0), (824 - r, 824), 255, -1)
    cv2.rectangle(mask, (0, r), (824, 824 - r), 255, -1)
    for cx, cy in [(r, r), (824 - r, r), (r, 824 - r), (824 - r, 824 - r)]:
        cv2.circle(mask, (cx, cy), r, 255, -1)
    icon = np.zeros((1024, 1024, 4), np.uint8)
    icon[100:924, 100:924, :3] = tile
    icon[100:924, 100:924, 3] = mask
    with tempfile.TemporaryDirectory() as tmp:
        iconset = os.path.join(tmp, "AppIcon.iconset")
        os.makedirs(iconset)
        for size in (16, 32, 128, 256, 512):
            for scale in (1, 2):
                px = size * scale
                name = f"icon_{size}x{size}{'@2x' if scale == 2 else ''}.png"
                cv2.imwrite(os.path.join(iconset, name), cv2.resize(icon, (px, px), interpolation=cv2.INTER_AREA))
        subprocess.run(["iconutil", "-c", "icns", iconset, "-o", out_icns], check=True)


def main():
    ap = argparse.ArgumentParser(description="Build Open Canvas.app")
    ap.add_argument("--dest", default=os.path.expanduser("~/Applications"))
    a = ap.parse_args()

    app = os.path.join(a.dest, "Open Canvas.app")
    if os.path.exists(app):
        shutil.rmtree(app)
    macos, res = os.path.join(app, "Contents", "MacOS"), os.path.join(app, "Contents", "Resources")
    os.makedirs(macos)
    os.makedirs(res)

    exe = os.path.join(macos, "OpenCanvas")
    with open(exe, "w") as f:
        f.write(LAUNCHER.format(repo=REPO))
    os.chmod(exe, 0o755)
    make_icon(os.path.join(res, "AppIcon.icns"))

    with open(os.path.join(app, "Contents", "Info.plist"), "wb") as f:
        plistlib.dump({
            "CFBundleName": "Open Canvas",
            "CFBundleDisplayName": "Open Canvas",
            "CFBundleIdentifier": "edu.bu.opencanvas",
            "CFBundleVersion": "1.0",
            "CFBundleShortVersionString": "1.0",
            "CFBundlePackageType": "APPL",
            "CFBundleExecutable": "OpenCanvas",
            "CFBundleIconFile": "AppIcon",
            "LSMinimumSystemVersion": "12.0",
            "NSHighResolutionCapable": True,
            "NSCameraUsageDescription": "Open Canvas watches your fingertip on the printed painting "
                                        "so it can play the sounds under your finger.",
        }, f)

    # Ad-hoc signature: lets macOS remember the camera permission for this app
    subprocess.run(["codesign", "--force", "--deep", "-s", "-", app], check=True, capture_output=True)
    print(f"built {app}")
    print("  start: double-click, Spotlight (Cmd+Space, 'Open Canvas'), or: open -a 'Open Canvas'")
    print("  log:   ~/Library/Logs/OpenCanvas.log")


if __name__ == "__main__":
    main()
